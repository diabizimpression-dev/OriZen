// Write SVGs to files
Object.keys(svgContents).forEach(key => {
  fs.writeFileSync(path.join(iconsDir, key + '.svg'), svgContents[key]);
});

// Helper function to escape special chars
function escapeRegExp(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Find all HTML files
const htmlFiles = fs.readdirSync(dir).filter(file => file.endsWith('.html'));

htmlFiles.forEach(file => {
  let content = fs.readFileSync(path.join(dir, file), 'utf8');
  let changed = false;

  Object.keys(emojiMap).forEach(emoji => {
    const svgName = emojiMap[emoji];
    // Regex to match the emoji
    const regex = new RegExp(escapeRegExp(emoji), 'g');
    if (regex.test(content)) {
      content = content.replace(regex, `<img src="img/icons/${svgName}.svg" alt="${svgName}" class="oz-icon" aria-hidden="true">`);
      changed = true;
    }
  });

  if (changed) {
    fs.writeFileSync(path.join(dir, file), content, 'utf8');
    console.log(`Updated ${file}`);
  }
});

